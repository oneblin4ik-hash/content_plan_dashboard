/**
 * Каталог вирусных шаблонов хуков и структур постов.
 *
 * Идея: вытащить виральные паттерны из системного промпта (где они
 * сейчас в FITNESS_BASE_SYSTEM зашиты как «рекомендация для модели»)
 * в видимую витрину, чтобы юзер выбирал визуально, как у конкурентов
 * (Notion templates / chatplace.io).
 *
 * Шаблон = паттерн заголовка + жёсткая структура поста. Юзер вводит
 * свою тему → сервер генерирует пост, точно следуя шаблону. См.
 * server/routers/content.ts:generatePost — он принимает opt-in
 * templateId и пристёгивает блок «обязательно следуй шаблону» к
 * task-промпту.
 *
 * Не делаем шаблоны Per-Niche до тех пор, пока не выйдем за фитнес —
 * пока примеры тяготеют к фитнес-блогерам, но сами паттерны
 * универсальны.
 */

