paths, captions, offset = [], [], 0.0
for c in CUTS:
    out = f"cuts/{c['name']}.mp4"
    subprocess.run(['ffmpeg','-y','-v','error','-ss',str(c['start']),'-to',str(c['end']),
        '-i',SRC,'-vf','scale=1080:1920:flags=lanczos,fps=30,format=yuv420p',
        '-c:v','libx264','-preset','slow','-crf','18',
        '-c:a','aac','-b:a','192k','-ar','48000','-ac','2',
        '-avoid_negative_ts','make_zero', out], check=True)
    paths.append(out)
    for word, ws, we in c['words']:
        captions.append({
            'word': word,
            'startMs': int(round((offset + ws - c['start']) * 1000)),
            'endMs':   int(round((offset + we - c['start']) * 1000)),
        })
    dur = c['end'] - c['start']
    print(f"  {c['name']:8} {c['start']:6.2f}-{c['end']:6.2f}  {dur:4.2f}s  ->  {offset:5.2f}-{offset+dur:5.2f}  ({len(c['words'])} слов)")
    offset += dur

open('concat.txt','w').write('\n'.join(f"file '{p}'" for p in paths) + '\n')
