import { z } from "zod";
import { protectedProcedure, router } from "../_core/trpc";
import { d1Query } from "../_core/d1";
import { invokeChatForUser, type ChatMessage } from "../_core/llm-guard";

/* ============================================================
   Контент-ассистент («Что постить сегодня?»).

   Stateless чат: клиент хранит историю сообщений и шлёт её целиком
   на каждый запрос (история короткая, обрезаем до последних N реплик).
   Сервер собирает контекст автора (последние темы из user_topics +
   голос + performance подмешивается внутри invokeChatForUser) и
   отвечает как персональный контент-стратег.

   Не сохраняем диалоги в БД — для MVP избыточно. Если понадобится
   история между сессиями, добавим таблицу assistant_threads.
   ============================================================ */

const ASSISTANT_TASK = `Ты — персональный контент-стратег и продюсер этого
автора. Твоя задача — помогать с идеями, форматами, заголовками, планом
публикаций и разбором, что и почему заходит аудитории.

Как отвечать:
- Конкретно и по делу. Никакой воды и общих советов «будьте искренними».
- Если просят идею поста — давай готовый цепляющий заголовок + 1-2 строки
  про подачу, а не «можно подумать о теме питания».
- Опирайся на нишу, аудиторию и голос автора из системного контекста.
- Если в контексте есть данные о том, что у автора заходило/не заходило —
  учитывай это в рекомендациях.
- Отвечай коротко: 2-5 абзацев максимум, можно списком. Это чат, не
  лонгрид.
- Пиши на «ты» если в профиле автора не указано иное.
- Если предлагаешь несколько идей — нумеруй их, чтобы автору было легко
  сослаться «давай разберём вторую».

Ты НЕ генерируешь полный готовый пост, если об этом прямо не просят —
твоя роль помочь думать и направлять. Для полноценной генерации у автора
есть отдельная Студия, можешь напомнить про неё в конце, если уместно.`;

/* Стартовые быстрые подсказки для UI — показываются над пустым чатом. */
export const ASSISTANT_SUGGESTIONS = [
  "Что мне выложить сегодня?",
  "Дай 3 идеи для Reels на этой неделе",
  "Какой формат сейчас лучше заходит?",
  "Разбери, почему мои посты слабо читают",
  "Придумай рубрику, которую можно вести постоянно",
];

const messageSchema = z.object({
  role: z.enum(["user", "assistant"]),
  content: z.string().min(1).max(4000),
});

export const assistantRouter = router({
  /* Возвращает стартовые подсказки + короткую сводку контекста, чтобы
     UI мог показать «я знаю о тебе: ниша X, N тем в библиотеке». */
  intro: protectedProcedure.query(async ({ ctx }) => {
    const topics = await d1Query<{ c: number }>(
      "SELECT COUNT(*) AS c FROM user_topics WHERE workspace_key = ?",
      [ctx.user.id],
    ).catch(() => [{ c: 0 }]);
    return {
      suggestions: ASSISTANT_SUGGESTIONS,
      topicsCount: Number(topics[0]?.c ?? 0),
    };
  }),

  ask: protectedProcedure
    .input(
      z.object({
        /* Вся история диалога; последний элемент — новая реплика
           юзера. Обрезаем на сервере до последних 16 сообщений, чтобы
           не раздувать промпт и расход токенов. */
        messages: z.array(messageSchema).min(1).max(40),
      }),
    )
    .mutation(async ({ ctx, input }) => {
      const history: ChatMessage[] = input.messages.slice(-16);

      /* Догружаем последние темы автора, чтобы ассистент не повторял
         уже имеющиеся идеи и мог на них ссылаться. Кладём отдельной
         system-вставкой через task. */
      let topicsHint = "";
      try {
        const recent = await d1Query<{ title: string }>(
          "SELECT title FROM user_topics WHERE workspace_key = ? ORDER BY created_at DESC LIMIT 20",
          [ctx.user.id],
        );
        if (recent.length > 0) {
          topicsHint =
            "\n\nТЕМЫ, КОТОРЫЕ У АВТОРА УЖЕ ЕСТЬ В БИБЛИОТЕКЕ (не повторяй их дословно, можешь развивать):\n" +
            recent.map((t) => `- ${t.title}`).join("\n");
        }
      } catch {
        /* библиотека недоступна — отвечаем без неё */
      }

      const { text, model } = await invokeChatForUser(
        ctx.user,
        ASSISTANT_TASK + topicsHint,
        history,
      );
      return { reply: text, model };
    }),
});
