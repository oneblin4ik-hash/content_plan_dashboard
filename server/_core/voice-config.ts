/**
 * Per-user voice config: что юзер настраивает в /voice, и как из этого
 * собирается системный промпт.
 *
 * Базовый промпт (FITNESS_BASE_SYSTEM) — универсальные правила для
 * фитнес-блогеров: антиAI-чек-лист, виральные паттерны заголовков,
 * запрет канцелярита. На него поверх накладывается per-user блок
 * с именем/нишей/ЦА/стилем — это и есть «настройка под себя».
 *
 * Поля держим плоскими и опциональными — что юзер не указал, в
 * промпт не уходит. Хранится в users.voice_json как JSON-блоб.
 */

export type VoiceConfig = {
  /** Имя автора / бренда (как обращаться от первого лица). */
  personaName?: string;
  /** Краткое позиционирование, 1-2 предложения. */
  bio?: string;
  /** Ниша: «похудение для женщин», «силовой тренинг», «йога» и т.п. */
  niche?: string;
  /** Описание ЦА. */
  audience?: string;
  /** Обращение к аудитории. */
  address?: "ты" | "вы";
  /** Стиль эмодзи в тексте. */
  emojiStyle?: "none" | "light" | "moderate" | "rich";
  /** Любимые обороты/фразочки (по одной на строку). */
  signaturePhrases?: string[];
  /** Слова, которые автор не использует. */
  forbiddenWords?: string[];
  /** Дефолтный CTA: «записаться», «написать в ЛС @handle». */
  defaultCta?: string;
};

export const DEFAULT_VOICE: VoiceConfig = {
  address: "ты",
  emojiStyle: "moderate",
};

/* Универсальный базовый промпт для фитнес-блогеров. Содержит только
   правила ремесла (как писать виральные хуки, антиAI, без канцелярита) —
   ничего про конкретного автора. Конкретика приходит из VoiceConfig
   ниже. */
export const FITNESS_BASE_SYSTEM = `Ты — копирайтер контента для фитнес-блогера.
Тема всегда вокруг тренировок, питания, восстановления, здоровья и
психологии трансформации.

ПРАВИЛА РЕМЕСЛА:
1. Не пиши как нейросеть. Избегай: «в современном мире», «однако», «таким
   образом», «следует отметить», «важно понимать», «данный», «как всем
   известно», «как мы уже выяснили», «является», «осуществить».
2. Короткие предложения. Один абзац = одна мысль. Без воды.
3. Кликбейт-хук на первой строке: цифра / отрицание / провокация /
   личная история / разбор мифа / вопрос-зеркало. Никогда не «Привет,
   друзья!» и не «Сегодня я расскажу…».
4. Конкретика > общие советы. «3 подхода по 12» вместо «делайте больше».
5. Никаких канцеляризмов и покровительства. Никакого агрессивного sales
   («купи сейчас», «успей до полуночи»).
6. Уважение к читателю: не объясняй очевидное, не учи жить.
7. Под конец — мягкий CTA на действие. Без «не забудьте подписаться» с
   восклицательными знаками.

ВИРАЛЬНЫЕ ПАТТЕРНЫ ЗАГОЛОВКОВ (опирайся на них в reels/cover):
- Отрицание популярного мифа: «Не делай Х. Делай Y».
- Цифра + противоположный результат: «3 ошибки, которые жгут мышцы».
- Личный опыт-крючок: «Я делал Х 5 лет. Зря».
- Вопрос-зеркало: «Почему ты не худеешь даже на дефиците?».
- Категория + неожиданное условие: «Топ-3 упражнения, которые ты
  делаешь зря».
- Боль ЦА в лоб: «Не похудеешь, пока…».`;

/* Из VoiceConfig собираем дополнительный блок, который дописывается к
   базовому промпту. Если юзер ничего не указал — блок будет пустой,
   и в промпт уходит только базовая часть.

   Этот блок намеренно идёт ПОСЛЕ FITNESS_BASE_SYSTEM — индивидуальные
   правила автора важнее общих. */
export function formatVoiceBlock(v: VoiceConfig | null | undefined): string {
  if (!v) return "";
  const lines: string[] = [];
  if (v.personaName) lines.push(`Автор: ${v.personaName}.`);
  if (v.bio) lines.push(`Позиционирование: ${v.bio}`);
  if (v.niche) lines.push(`Ниша: ${v.niche}`);
  if (v.audience) lines.push(`Целевая аудитория: ${v.audience}`);
  if (v.address) {
    lines.push(
      v.address === "вы"
        ? "Обращение к читателю — на «вы», уважительно."
        : "Обращение к читателю — на «ты», по-дружески.",
    );
  }
  if (v.emojiStyle) {
    const map = {
      none: "Без эмодзи.",
      light: "Эмодзи редко, только когда они помогают смыслу.",
      moderate: "Эмодзи в меру: подчёркивают эмоции, не заменяют слова.",
      rich: "Эмодзи активно — для ритма и эмоциональных акцентов.",
    } as const;
    lines.push(map[v.emojiStyle]);
  }
  if (v.signaturePhrases && v.signaturePhrases.length > 0) {
    lines.push(
      "Любимые обороты автора (используй их естественно, не натужно): " +
        v.signaturePhrases.slice(0, 12).join(" / "),
    );
  }
  if (v.forbiddenWords && v.forbiddenWords.length > 0) {
    lines.push(
      "Запрещённые слова и обороты (не используй ни при каких условиях): " +
        v.forbiddenWords.slice(0, 30).join(", "),
    );
  }
  if (v.defaultCta) {
    lines.push(`Стандартный CTA автора: «${v.defaultCta}».`);
  }
  if (lines.length === 0) return "";
  return `\n\nПЕРСОНАЛЬНЫЙ ПРОФИЛЬ АВТОРА (важнее общих правил выше):\n${lines.join("\n")}`;
}

export function buildSystemPrompt(voice: VoiceConfig | null): string {
  return FITNESS_BASE_SYSTEM + formatVoiceBlock(voice);
}
