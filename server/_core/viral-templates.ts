/* Возвращает блок текста, который content router добавляет к task-
   промпту. Если id неизвестен — пустая строка (на «случайно битый
   запрос с клиента» не падаем). */
export function templateBlock(templateId: string | undefined): string {
  if (!templateId) return "";
  const s = STRUCTURES[templateId];
  if (!s) return "";
  return `\n\nОБЯЗАТЕЛЬНО следуй вирусному шаблону ${templateId}. Жёсткая
структура поста (НЕ отклоняйся, каждый блок — отдельный абзац):
${s}`;
}
