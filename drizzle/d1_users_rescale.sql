-- Рескейл баланса токенов в «пользовательскую» шкалу 1:10.
--
-- Было: 1 токен баланса = 1 реальный токен Gemini (триал 30 000).
-- Стало: 1 токен баланса = 10 реальных токенов Gemini (триал 3 000).
--
-- Делим существующие балансы на 10 (с округлением вверх, чтобы никто
-- не потерял в результате округления). Поскольку списание теперь тоже
-- делится на 10, число доступных генераций у юзера не меняется —
-- меняются только цифры на балансе (становятся короче).
--
-- Идемпотентность: эту миграцию нельзя гонять дважды (повторный запуск
-- поделит баланс ещё раз). Запускается ОДИН РАЗ при переходе на новую
-- шкалу. Новые юзеры уже создаются в новой шкале (DEFAULT 3000).
UPDATE users
SET
  tokens_remaining = MAX(1, CAST((tokens_remaining + 9) / 10 AS INTEGER)),
  tokens_used_total = CAST((tokens_used_total + 9) / 10 AS INTEGER);
